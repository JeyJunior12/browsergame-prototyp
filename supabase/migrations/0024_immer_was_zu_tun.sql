create or replace function public.kiez_daily_tasks_ensure(uid uuid)
returns void language plpgsql security definer set search_path to 'public' as $function$
declare pool text[] := array['bottles','beg','bin','npc','crime','wins','sort']; tg int[] := array[60,3,5,2,2,1,1]; picked int[]; i int; k int;
begin
  if exists(select 1 from public.daily_tasks where user_id=uid and day=current_date) then return; end if;
  -- 3 verschiedene Aufgaben, pro Spieler und Tag fest (Zufall mit Tages-Samen)
  select array_agg(x) into picked from (select x from generate_series(1,7) x order by md5(uid::text||current_date::text||x::text) limit 3) s;
  for i in 1..3 loop
    k := picked[i];
    insert into public.daily_tasks(user_id,day,slot,kind,target) values(uid,current_date,i,pool[k],tg[k]) on conflict do nothing;
  end loop;
end $function$;

