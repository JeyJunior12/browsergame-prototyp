create or replace function public.daily_tasks_status()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare me uuid := auth.uid(); wk date := public.kiez_week(current_date);
begin
  if me is null then raise exception 'Nicht angemeldet'; end if;
  perform public.kiez_daily_tasks_ensure(me);
  return jsonb_build_object('tasks',(select jsonb_agg(jsonb_build_object('slot',slot,'kind',kind,'target',target,'progress',progress,'claimed',claimed) order by slot)
      from public.daily_tasks where user_id=me and day=current_date),
    'week_done',(select count(*) from public.daily_tasks where user_id=me and day>=wk and claimed),
    'week_bonus_claimed',(select week_bonus_week from public.profiles where id=me)=wk);
end $function$;

create or replace function public.claim_daily_task(task_slot integer)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; t public.daily_tasks; wk date := public.kiez_week(current_date); n int; bonus boolean := false;
begin
  p := public.kiez_actor();
  select * into t from public.daily_tasks where user_id=p.id and day=current_date and slot=task_slot for update;
  if t.user_id is null then raise exception 'Diese Aufgabe gibt es heute nicht'; end if;
  if t.claimed then raise exception 'Schon abgeholt'; end if;
  if t.progress < t.target then raise exception 'Noch nicht geschafft (% von %)', t.progress, t.target; end if;
  update public.daily_tasks set claimed=true where user_id=p.id and day=current_date and slot=task_slot;
  update public.profiles set bottlecaps=bottlecaps+2, xp=xp+20 where id=p.id;
  perform public.kiez_pay(p.id, 2.00);
  -- Wochenbonus: 15 Tagesaufgaben in einer Woche → 25 Kronkorken
  select count(*) into n from public.daily_tasks where user_id=p.id and day>=wk and claimed;
  if n >= 15 and p.week_bonus_week is distinct from wk then
    update public.profiles set bottlecaps=bottlecaps+25, week_bonus_week=wk where id=p.id; bonus := true;
  end if;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('caps',2,'xp',20,'money',2,'week_bonus',bonus,'profile',to_jsonb(p));
end $function$;

-- ---------- 38: Mülltonne ----------
alter table public.profiles add column if not exists bin_at timestamptz;
create or replace function public.dig_bin()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; r numeric := random(); what text; amt numeric := 0; pl text; pln text;
begin
  p := public.kiez_actor();
  perform public.kiez_assert_free(p);
  if p.bin_at > now()-interval '3 minutes' then raise exception 'Die Tonne ist leer – in % Sek. kommt neuer Müll', ceil(extract(epoch from (p.bin_at+interval '3 minutes'-now()))); end if;
  update public.profiles set bin_at=now(), cleanliness=greatest(0,cleanliness-2) where id=p.id;
  if r < 0.08 then
    what := 'ratte'; update public.profiles set energy=greatest(0,energy-5), cleanliness=greatest(0,cleanliness-5) where id=p.id;
  elsif r < 0.10 then
    what := 'plunder'; pl := public.kiez_random_plunder(); perform public.kiez_give_plunder(p.id,pl); select name into pln from public.plunder_catalog where id=pl;
  elsif r < 0.25 then
    what := 'kronkorken'; amt := 1+floor(random()*2); update public.profiles set bottlecaps=bottlecaps+amt::int where id=p.id;
  elsif r < 0.35 then
    what := 'geld'; amt := round((0.10+random()*0.90)::numeric,2); perform public.kiez_pay(p.id,amt);
  else
    what := 'flaschen'; amt := 1+floor(random()*5); update public.profiles set bottles=bottles+amt::int where id=p.id;
    insert into public.daily_missions(user_id,progress) values(p.id,amt::int)
    on conflict(user_id,mission_day) do update set progress=daily_missions.progress+excluded.progress;
  end if;
  perform public.kiez_act(p.id,'bin');
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('what',what,'amount',amt,'plunder',pl,'plunder_name',pln,'profile',to_jsonb(p));
end $function$;

