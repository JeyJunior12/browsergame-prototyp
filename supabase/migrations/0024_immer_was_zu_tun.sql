-- Kampf gegen einen Computer-Gegner: 10 Energie, pro Gegner alle 10 Min.
create or replace function public.fight_npc(npc_id text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; n record; mine int; theirs int; won boolean; loot numeric := 0; gx int := 0;
begin
  p := public.kiez_actor();
  perform public.kiez_assert_free(p);
  select * into n from public.kiez_npcs() x where x.id=npc_id;
  if n.id is null then raise exception 'Diesen Gegner gibt es nicht'; end if;
  if exists(select 1 from public.npc_fights where user_id=p.id and npc=npc_id and created_at>now()-interval '10 minutes') then
    raise exception '% hat erst mal genug – in ein paar Minuten wieder', n.name; end if;
  if p.energy < 10 then raise exception 'Du brauchst 10 Energie'; end if;
  mine := round((public.kiez_attack_power(p))*(0.75+random()*0.5));
  theirs := round((public.kiez_attack_power(p)+public.kiez_defense_power(p))/2.0*n.factor*(0.75+random()*0.5));
  won := mine >= theirs;
  if won then loot := round((n.loot_base*(1+p.level*0.05)*(0.8+random()*0.4))::numeric,2); gx := n.xp; perform public.kiez_pay(p.id,loot); end if;
  update public.profiles set energy=energy-10, xp=xp+gx, cleanliness=greatest(0,cleanliness-2) where id=p.id returning * into p;
  insert into public.npc_fights(user_id,npc,won,loot,xp) values(p.id,npc_id,won,loot,gx);
  if won then perform public.kiez_act(p.id,'npc'); end if;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('won',won,'npc',n.name,'mine',mine,'theirs',theirs,'loot',loot,'xp',gx,'profile',to_jsonb(p));
end $function$;

