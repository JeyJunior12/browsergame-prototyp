-- Nach dem Ausladen (collection_ready_at gesetzt) mit 35 % ein Ereignis zur Entscheidung
create or replace function public.tour_event()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; e public.tour_events; k text;
begin
  select * into p from public.profiles where id=auth.uid();
  if p.id is null then raise exception 'Nicht angemeldet'; end if;
  if p.collection_ready_at is null or p.collection_ready_at < now()-interval '10 minutes' then return null; end if;
  select * into e from public.tour_events where user_id=p.id and tour_at=p.collection_ready_at;
  if e.user_id is null then
    k := case when random() < 0.35 then (array['hund','polizei','container'])[1+floor(random()*3)::int] else 'keins' end;
    insert into public.tour_events(user_id,tour_at,kind,resolved) values(p.id,p.collection_ready_at,k,k='keins') on conflict do nothing returning * into e;
  end if;
  if e.resolved then return null; end if;
  return jsonb_build_object('kind',e.kind,
    'text',case e.kind when 'hund' then 'Ein bissiger Hund bewacht einen Container voller Flaschen.' when 'polizei' then 'Eine Streife hält an und mustert deinen Einkaufswagen.' else 'Ein Container quillt über vor Pfand – aber es stinkt bestialisch.' end,
    'options',case e.kind when 'hund' then jsonb_build_array('Wurst geben (0,50 €)','Weggehen','Es drauf ankommen lassen')
                          when 'polizei' then jsonb_build_array('Freundlich grüßen','Wegrennen','Pfandbon zeigen')
                          else jsonb_build_array('Reinklettern','Nur oben rausgreifen','Liegen lassen') end);
end $function$;

create or replace function public.resolve_tour_event(choice integer)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; e public.tour_events; msg text; b int := 0;
begin
  p := public.kiez_actor();
  select * into e from public.tour_events where user_id=p.id and tour_at=p.collection_ready_at and not resolved for update;
  if e.user_id is null then raise exception 'Kein offenes Ereignis'; end if;
  if choice not between 1 and 3 then raise exception 'Ungültige Wahl'; end if;
  if e.kind='hund' then
    if choice=1 then
      if p.money < 0.50 then raise exception 'Dafür reicht deine Kohle nicht'; end if;
      update public.profiles set money=money-0.50 where id=p.id; b := 15; msg := 'Der Hund frisst, du räumst den Container leer: +15 Flaschen.';
    elsif choice=2 then msg := 'Du gehst lieber. Nichts passiert.';
    elsif random() < 0.5 then b := 25; msg := 'Der Hund pennt – du holst dir 25 Flaschen!';
    else update public.profiles set energy=greatest(0,energy-5), cleanliness=greatest(0,cleanliness-10) where id=p.id; msg := 'Autsch, gebissen! −5 Energie, −10 % Sauberkeit.'; end if;
  elsif e.kind='polizei' then
    if choice=1 then update public.profiles set xp=xp+3 where id=p.id; msg := 'Die Beamten nicken dir zu. +3 Punkte für gutes Benehmen.';
    elsif choice=2 then
      if random() < 0.6 then msg := 'Du bist schneller – weg bist du.';
      else update public.profiles set money=greatest(0,money-2) where id=p.id; msg := 'Erwischt: 2 € Verwarngeld.'; end if;
    else update public.profiles set xp=xp+5 where id=p.id; msg := 'Du zeigst den Pfandbon – alles in Ordnung. +5 Punkte.'; end if;
  else
    if choice=1 then b := 30; update public.profiles set cleanliness=greatest(0,cleanliness-15) where id=p.id; msg := 'Bis zur Hüfte im Müll: +30 Flaschen, −15 % Sauberkeit.';
    elsif choice=2 then b := 10; msg := 'Ein paar Flaschen von oben: +10.';
    else msg := 'Zu eklig. Du lässt es liegen.'; end if;
  end if;
  if b > 0 then
    update public.profiles set bottles=bottles+b where id=p.id;
    insert into public.daily_missions(user_id,progress) values(p.id,b) on conflict(user_id,mission_day) do update set progress=daily_missions.progress+excluded.progress;
  end if;
  update public.tour_events set resolved=true, outcome=msg where user_id=p.id and tour_at=e.tour_at;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('message',msg,'bottles',b,'profile',to_jsonb(p));
end $function$;

-- ---------- 40: seltene Chancen („Tourist verliert 2 €“) ----------
create table if not exists public.chances(
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(12,2) not null, text text not null,
  created_at timestamptz not null default now(), expires_at timestamptz not null, claimed boolean not null default false);
create index if not exists chances_user on public.chances(user_id, created_at desc);
alter table public.chances enable row level security;
revoke all on public.chances from anon, authenticated;

-- Der Client fragt höchstens alle 2 Min.; Server entscheidet selten (8 %), höchstens 3 am Tag
create or replace function public.chance_poll()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare me uuid := auth.uid(); c public.chances; t text[] := array['Ein Tourist verliert 2 € – schnell aufheben!','Aus einem Automaten fällt Wechselgeld!','Ein Betrunkener lässt Kleingeld fallen!'];
begin
  if me is null then raise exception 'Nicht angemeldet'; end if;
  select * into c from public.chances where user_id=me and not claimed and expires_at>now() order by id desc limit 1;
  if c.id is not null then return jsonb_build_object('id',c.id,'text',c.text,'amount',c.amount,'expires_at',c.expires_at); end if;
  if exists(select 1 from public.chances where user_id=me and created_at>now()-interval '2 minutes') then return null; end if;
  if (select count(*) from public.chances where user_id=me and created_at>current_date) >= 3 then return null; end if;
  if random() >= 0.08 then
    insert into public.chances(user_id,amount,text,expires_at,claimed) values(me,0,'',now(),true); return null; end if;
  insert into public.chances(user_id,amount,text,expires_at) values(me,round((1+random()*2)::numeric,2),t[1+floor(random()*3)::int],now()+interval '15 seconds') returning * into c;
  return jsonb_build_object('id',c.id,'text',c.text,'amount',c.amount,'expires_at',c.expires_at);
end $function$;

create or replace function public.chance_claim(chance bigint)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; c public.chances;
begin
  p := public.kiez_actor();
  select * into c from public.chances where id=chance and user_id=p.id for update;
  if c.id is null or c.claimed then raise exception 'Zu spät – jemand anderes war schneller'; end if;
  if c.expires_at < now() then update public.chances set claimed=true where id=c.id; raise exception 'Zu spät – das Geld ist weg'; end if;
  update public.chances set claimed=true where id=c.id;
  perform public.kiez_pay(p.id, c.amount);
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('amount',c.amount,'profile',to_jsonb(p));
end $function$;

-- ---------- 43: Flaschen-Sortierspiel (30 Sek.) ----------
create table if not exists public.sort_games(
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  items text not null, started_at timestamptz not null default now(), finished boolean not null default false, score integer);
alter table public.sort_games enable row level security;
revoke all on public.sort_games from anon, authenticated;

-- 20 Gegenstände: g = Glas, p = Plastik, d = Dose. Alle 20 Min. einmal.
create or replace function public.sort_game_start()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; seq text := ''; i int; g public.sort_games;
begin
  p := public.kiez_actor();
  if exists(select 1 from public.sort_games where user_id=p.id and started_at>now()-interval '20 minutes') then
    raise exception 'Die Sortieranlage ist noch belegt – in % Min. wieder', ceil(extract(epoch from ((select max(started_at) from public.sort_games where user_id=p.id)+interval '20 minutes'-now()))/60); end if;
  for i in 1..20 loop seq := seq || (array['g','p','d'])[1+floor(random()*3)::int]; end loop;
  insert into public.sort_games(user_id,items) values(p.id,seq) returning * into g;
  return jsonb_build_object('id',g.id,'items',seq,'seconds',30);
end $function$;

create or replace function public.sort_game_finish(game bigint, answers text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; g public.sort_games; right_ int := 0; i int; b int;
begin
  p := public.kiez_actor();
  select * into g from public.sort_games where id=game and user_id=p.id for update;
  if g.id is null or g.finished then raise exception 'Dieses Spiel ist schon vorbei'; end if;
  update public.sort_games set finished=true where id=g.id;
  if now() > g.started_at + interval '35 seconds' then raise exception 'Zeit abgelaufen – das zählt nicht'; end if;
  for i in 1..least(20,char_length(coalesce(answers,''))) loop
    if substr(answers,i,1) = substr(g.items,i,1) then right_ := right_+1; end if;
  end loop;
  b := right_;  -- jede richtig sortierte Flasche = 1 Pfandflasche
  update public.sort_games set score=right_ where id=g.id;
  if b > 0 then
    update public.profiles set bottles=bottles+b where id=p.id;
    insert into public.daily_missions(user_id,progress) values(p.id,b) on conflict(user_id,mission_day) do update set progress=daily_missions.progress+excluded.progress;
  end if;
  perform public.kiez_act(p.id,'sort');
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('right',right_,'bottles',b,'profile',to_jsonb(p));
end $function$;

