create or replace function public.world_boss_hit()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; b public.world_boss; wk date := public.kiez_week(current_date); dmg int; h public.world_boss_hits; x record;
begin
  p := public.kiez_actor();
  perform public.kiez_assert_free(p);
  b := public.kiez_world_boss();
  select * into b from public.world_boss where week_start=wk for update;
  if b.defeated_at is not null then raise exception 'Der Kiezboss liegt schon am Boden – nächste Woche kommt ein neuer'; end if;
  select * into h from public.world_boss_hits where week_start=wk and user_id=p.id;
  if h.last_hit_at > now()-interval '1 hour' then raise exception 'Du kannst erst in % Min. wieder zuschlagen', ceil(extract(epoch from (h.last_hit_at+interval '1 hour'-now()))/60); end if;
  if p.energy < 10 then raise exception 'Du brauchst 10 Energie'; end if;
  dmg := greatest(1, round(public.kiez_attack_power(p)*(0.8+random()*0.4)))::int;
  update public.profiles set energy=energy-10 where id=p.id;
  insert into public.world_boss_hits(week_start,user_id,damage,hits,last_hit_at) values(wk,p.id,dmg,1,now())
  on conflict (week_start,user_id) do update set damage=world_boss_hits.damage+dmg, hits=world_boss_hits.hits+1, last_hit_at=now();
  update public.world_boss set hp=greatest(0,hp-dmg), defeated_at=case when hp-dmg<=0 then now() end where week_start=wk returning * into b;
  perform public.kiez_act(p.id,'npc');
  if b.defeated_at is not null then
    for x in select user_id, damage from public.world_boss_hits where week_start=wk loop
      update public.profiles set bottlecaps=bottlecaps+15, xp=xp+150 where id=x.user_id;
      perform public.kiez_pay(x.user_id, 5.00);
      perform public.kiez_notify(x.user_id,'boss','Der Kiezboss „'||b.name||'“ ist besiegt! Für dich: 5 €, 15 Kronkorken, 150 Punkte.');
    end loop;
  end if;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('damage',dmg,'hp',b.hp,'max_hp',b.max_hp,'defeated',b.defeated_at is not null,'profile',to_jsonb(p));
end $function$;

