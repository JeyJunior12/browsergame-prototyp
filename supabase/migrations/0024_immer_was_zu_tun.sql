    'boss_ready_at', (select last_hit_at+interval '1 hour' from public.world_boss_hits where week_start=public.kiez_week(current_date) and user_id=p.id and last_hit_at>now()-interval '1 hour'),
    'flash', jsonb_build_object('kind', public.kiez_flash_kind(p.id,fslot), 'ends_at', to_timestamp((fslot+1)*300),
       'done', exists(select 1 from public.flash_tasks f where f.user_id=p.id and f.slot=fslot)),
