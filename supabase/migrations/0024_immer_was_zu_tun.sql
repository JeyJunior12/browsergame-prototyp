create or replace function public.kiez_flash_slot() returns bigint language sql stable as $$ select floor(extract(epoch from now())/300)::bigint $$;
create or replace function public.kiez_flash_kind(uid uuid, slot bigint)
returns text language sql immutable as $$
  select (array['bin','beg','bottles','npc','crime'])[1 + abs(hashtext(uid::text||slot::text)) % 5]
$$;

-- Jede Aktion: Tagesaufgaben, Blitzauftrag, Strähne weiterzählen
create or replace function public.kiez_act(uid uuid, k text, amount integer default 1)
returns void language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; fslot bigint := public.kiez_flash_slot(); st int;
begin
  if uid is null or amount <= 0 then return; end if;
  insert into public.kiez_actions(user_id,kind,amount) values(uid,k,amount);
  perform public.kiez_daily_tasks_ensure(uid);
  update public.daily_tasks set progress=least(target,progress+amount) where user_id=uid and day=current_date and kind=k;
  -- Blitzauftrag: passt die Aktion zum aktuellen Auftrag → erledigt, 1 Kronkorken + 0,50 €
  if public.kiez_flash_kind(uid,fslot)=k and not exists(select 1 from public.flash_tasks f where f.user_id=uid and f.slot=fslot) then
    insert into public.flash_tasks(user_id,slot,kind,done_at) values(uid,fslot,k,now());
    update public.profiles set bottlecaps=bottlecaps+1 where id=uid;
    perform public.kiez_pay(uid,0.50);
  end if;
  -- Glückssträhne: jede 5. Aktion in Folge (Abstand ≤ 5 Min.) bringt 1 Kronkorken
  select * into p from public.profiles where id=uid;
  st := case when p.streak_at > now()-interval '5 minutes' then p.streak+1 else 1 end;
  update public.profiles set streak=st, streak_at=now(), bottlecaps=bottlecaps+case when st % 5 = 0 then 1 else 0 end where id=uid;
end $function$;
revoke execute on function public.kiez_act(uuid,text,integer) from public, anon, authenticated;

-- Bestehende Aktionen anschließen (Trigger auf die vorhandenen Protokolle)
create or replace function public.kiez_act_trigger()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare d int;
begin
  if tg_table_name='daily_missions' then
    d := new.progress;
    if tg_op='UPDATE' then d := d - old.progress; end if;
    if d > 0 then perform public.kiez_act(new.user_id,'bottles',d); end if;
  elsif tg_table_name='beg_log' then perform public.kiez_act(new.user_id,'beg');
  elsif tg_table_name='fights' then perform public.kiez_act(new.winner_id,'wins');
  elsif tg_table_name='side_action_log' and new.action_type like 'crime:%' and new.success then perform public.kiez_act(new.user_id,'crime');
  end if;
  return new;
end $function$;
drop trigger if exists daily_missions_act on public.daily_missions;
