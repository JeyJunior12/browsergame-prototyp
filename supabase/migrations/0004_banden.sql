create or replace function public.post_gang_message(message_body text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.gang_members; clean text := trim(coalesce(message_body,'')); mid bigint;
begin
  p := public.kiez_actor();
