-- ---------- Helfer ----------
create or replace function public.kiez_gang_log(gid uuid, uid uuid, k text, amt numeric, txt text)
returns void language sql as $$ insert into public.gang_log(gang_id,user_id,kind,amount,info) values(gid,uid,k,coalesce(amt,0),coalesce(txt,'')) $$;

-- eigene Mitgliedschaft; wirft Fehler, wenn Rolle nicht reicht
create or replace function public.kiez_my_gang(min_role text default 'member')
returns public.gang_members language plpgsql security definer set search_path to 'public' as $function$
declare m public.gang_members; rank_of jsonb := '{"member":1,"officer":2,"co":3,"owner":4}';
begin
  select * into m from public.gang_members where user_id=auth.uid();
  if m.gang_id is null then raise exception 'Du bist in keiner Bande'; end if;
  if (rank_of->>m.role)::int < (rank_of->>min_role)::int then raise exception 'Dafür reicht dein Rang in der Bande nicht'; end if;
  return m;
end $function$;

create or replace function public.kiez_join(gid uuid, uid uuid)
returns void language plpgsql security definer set search_path to 'public' as $function$
begin
  if exists(select 1 from public.gang_members where user_id=uid) then raise exception 'Schon in einer Bande'; end if;
  if (select count(*) from public.gang_members where gang_id=gid)>=30 then raise exception 'Die Bande ist voll (30 Mitglieder)'; end if;
  insert into public.gang_members(gang_id,user_id,role) values(gid,uid,'member');
  delete from public.gang_requests where user_id=uid;
  perform public.kiez_gang_log(gid,uid,'join',0,'ist beigetreten');
end $function$;

-- ---------- Gruenden / Beitreten / Verlassen ----------
create or replace function public.create_gang(gang_name text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare g public.gangs; p public.profiles; cost numeric := 50; clean text := trim(gang_name);
begin
  p := public.kiez_actor();
  if exists(select 1 from public.gang_members where user_id=p.id) then raise exception 'Du bist bereits in einer Bande'; end if;
  if not public.valid_game_name(clean,3,30) then raise exception 'Bandenname: 3 bis 30 Zeichen, nur Buchstaben, Zahlen, Leerzeichen, _ . -'; end if;
  if exists(select 1 from public.gangs where lower(name)=lower(clean)) then raise exception 'Diesen Bandennamen gibt es schon'; end if;
  if p.money<cost then raise exception 'Eine Bandengründung kostet 50 €'; end if;
  insert into public.gangs(name,owner_id) values(clean,p.id) returning * into g;
  insert into public.gang_members(gang_id,user_id,role) values(g.id,p.id,'owner');
  delete from public.gang_requests where user_id=p.id;
  update public.profiles set money=money-cost where id=p.id;
  perform public.kiez_gang_log(g.id,p.id,'create',0,'hat die Bande gegründet');
  return to_jsonb(g);
end $function$;

-- Beitreten: offene Bande oder vorliegende Einladung
create or replace function public.join_gang(wanted_gang uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; g public.gangs;
begin
  p := public.kiez_actor();
  select * into g from public.gangs where id=wanted_gang for update;
  if g.id is null then raise exception 'Bande unbekannt'; end if;
  if exists(select 1 from public.gang_members where user_id=p.id) then raise exception 'Du bist bereits in einer Bande'; end if;
  if not g.is_open and not exists(select 1 from public.gang_requests where gang_id=g.id and user_id=p.id and kind='invite') then
    raise exception 'Diese Bande nimmt nur mit Einladung auf – bewirb dich'; end if;
  perform public.kiez_join(g.id,p.id);
  return jsonb_build_object('joined',g.id,'name',g.name);
end $function$;

create or replace function public.gang_apply(wanted_gang uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles;
begin
  p := public.kiez_actor();
  if not exists(select 1 from public.gangs where id=wanted_gang) then raise exception 'Bande unbekannt'; end if;
  if exists(select 1 from public.gang_members where user_id=p.id) then raise exception 'Du bist bereits in einer Bande'; end if;
  if (select count(*) from public.gang_requests where user_id=p.id and kind='apply')>=3 then raise exception 'Höchstens 3 offene Bewerbungen'; end if;
  insert into public.gang_requests(gang_id,user_id,kind,created_by) values(wanted_gang,p.id,'apply',p.id)
  on conflict (gang_id,user_id) do nothing;
  if not found then raise exception 'Da läuft schon eine Anfrage'; end if;
  return jsonb_build_object('applied',wanted_gang);
end $function$;

create or replace function public.gang_invite(target_id uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.gang_members;
begin
  p := public.kiez_actor();
  m := public.kiez_my_gang('officer');
  if not exists(select 1 from public.profiles where id=target_id and not is_banned) then raise exception 'Spieler unbekannt'; end if;
  if exists(select 1 from public.gang_members where user_id=target_id) then raise exception 'Der Spieler ist schon in einer Bande'; end if;
  -- Bewerbung liegt vor -> direkt aufnehmen
  if exists(select 1 from public.gang_requests where gang_id=m.gang_id and user_id=target_id and kind='apply') then
    perform public.kiez_join(m.gang_id,target_id);
    return jsonb_build_object('status','joined');
  end if;
  insert into public.gang_requests(gang_id,user_id,kind,created_by) values(m.gang_id,target_id,'invite',p.id)
  on conflict (gang_id,user_id) do nothing;
  if not found then raise exception 'Der Spieler ist schon eingeladen'; end if;
  perform public.kiez_gang_log(m.gang_id,p.id,'invite',0,'hat '||(select username from public.profiles where id=target_id)||' eingeladen');
  return jsonb_build_object('status','invited');
end $function$;

-- Anfrage/Einladung zurueckziehen oder ablehnen (Spieler selbst oder Bandenfuehrung)
create or replace function public.gang_request_delete(wanted_gang uuid, target_id uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; allowed boolean;
begin
  p := public.kiez_actor();
  allowed := target_id=p.id or exists(select 1 from public.gang_members where gang_id=wanted_gang and user_id=p.id and role in ('owner','co','officer'));
  if not allowed then raise exception 'Das darfst du nicht'; end if;
  delete from public.gang_requests where gang_id=wanted_gang and user_id=target_id;
  return jsonb_build_object('deleted',true);
end $function$;

drop function if exists public.leave_gang();
create or replace function public.leave_gang()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.gang_members; members int;
begin
  p := public.kiez_actor();
  m := public.kiez_my_gang('member');
  select count(*) into members from public.gang_members where gang_id=m.gang_id;
  if m.role='owner' and members>1 then raise exception 'Übergib erst die Chefrolle an ein anderes Mitglied'; end if;
  delete from public.gang_members where user_id=p.id;
  if members=1 then delete from public.gangs where id=m.gang_id;
  else perform public.kiez_gang_log(m.gang_id,p.id,'leave',0,'hat die Bande verlassen'); end if;
  return jsonb_build_object('left',m.gang_id);
end $function$;

create or replace function public.kick_gang_member(target_id uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.gang_members; t public.gang_members; rank_of jsonb := '{"member":1,"officer":2,"co":3,"owner":4}';
begin
  p := public.kiez_actor();
  m := public.kiez_my_gang('co');
  select * into t from public.gang_members where user_id=target_id and gang_id=m.gang_id;
  if t.user_id is null then raise exception 'Nicht in deiner Bande'; end if;
  if (rank_of->>t.role)::int >= (rank_of->>m.role)::int then raise exception 'Du kannst nur niedrigere Ränge rauswerfen'; end if;
  delete from public.gang_members where user_id=target_id;
  perform public.kiez_gang_log(m.gang_id,p.id,'kick',0,'hat '||(select username from public.profiles where id=target_id)||' rausgeworfen');
  return jsonb_build_object('kicked',target_id);
end $function$;

create or replace function public.set_gang_role(target_id uuid, new_role text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.gang_members;
begin
  p := public.kiez_actor();
  m := public.kiez_my_gang('owner');
  if new_role not in ('co','officer','member','owner') then raise exception 'Unbekannter Rang'; end if;
  if target_id=p.id then raise exception 'Deinen eigenen Rang kannst du nicht ändern'; end if;
  if not exists(select 1 from public.gang_members where user_id=target_id and gang_id=m.gang_id) then raise exception 'Nicht in deiner Bande'; end if;
  if new_role='owner' then
    update public.gang_members set role='co' where user_id=p.id;
    update public.gangs set owner_id=target_id where id=m.gang_id;
  end if;
  update public.gang_members set role=new_role where user_id=target_id;
  perform public.kiez_gang_log(m.gang_id,p.id,'role',0,(select username from public.profiles where id=target_id)||' ist jetzt '||
    case new_role when 'owner' then 'Chef' when 'co' then 'Vize' when 'officer' then 'Offizier' else 'Mitglied' end);
  return jsonb_build_object('role',new_role);
end $function$;

create or replace function public.update_gang_profile(new_description text, open_for_all boolean)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.gang_members; g public.gangs; d text := trim(coalesce(new_description,''));
