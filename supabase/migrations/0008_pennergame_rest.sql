create or replace function public.post_board(message_body text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; clean text := trim(coalesce(message_body,'')); pid bigint;
begin
  p := public.kiez_actor();
  if char_length(clean) not between 2 and 300 then raise exception 'Beitrag muss 2 bis 300 Zeichen haben'; end if;
  if exists(select 1 from public.board_posts where user_id=p.id and created_at>now()-interval '30 seconds') then raise exception 'Nicht so schnell – warte 30 Sekunden'; end if;
  insert into public.board_posts(user_id,body) values(p.id,clean) returning id into pid;
  return jsonb_build_object('id',pid);
end $function$;

