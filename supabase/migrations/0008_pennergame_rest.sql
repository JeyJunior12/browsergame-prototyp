create or replace function public.set_avatar(image text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles;
begin
  p := public.kiez_actor();
  if image is not null and (image !~ '^data:image/(jpeg|png|webp);base64,[A-Za-z0-9+/=]+$' or char_length(image)>120000) then
    raise exception 'Bild ungültig oder zu groß'; end if;
  update public.profiles set avatar=image where id=p.id returning * into p;
  return jsonb_build_object('ok',true);
end $function$;

