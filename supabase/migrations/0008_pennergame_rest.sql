create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare wanted text := trim(coalesce(new.raw_user_meta_data->>'username','')); ref uuid;
begin
  if not public.valid_game_name(wanted,3,20)
     or exists(select 1 from public.profiles where lower(username)=lower(wanted)) then
    wanted := 'Kiezkind_' || substr(new.id::text,1,6);
  end if;
  select id into ref from public.profiles where lower(username)=lower(trim(coalesce(new.raw_user_meta_data->>'ref',''))) and not is_banned;
  insert into public.profiles(id, username, referred_by) values(new.id, wanted, ref);
  if ref is not null then perform public.kiez_notify(ref,'werben',wanted||' ist über deinen Werbelink in den Kiez gekommen. Erreicht '||wanted||' Level 5, bekommst du 25 Kronkorken.'); end if;
  return new;
end $function$;

create or replace function public.kiez_referral_reward() returns trigger language plpgsql security definer set search_path to 'public' as $function$
begin
  if new.level>=5 and old.level<5 and new.referred_by is not null and not new.referral_rewarded then
    update public.profiles set bottlecaps=bottlecaps+25, xp=xp+100 where id=new.referred_by;
    update public.profiles set referral_rewarded=true, bottlecaps=bottlecaps+10 where id=new.id;
    perform public.kiez_notify(new.referred_by,'werben','🎉 '||new.username||' hat Level 5 erreicht: +25 Kronkorken und +100 Punkte für dich!');
    perform public.kiez_notify(new.id,'werben','🎉 Level 5! Als Geworbener bekommst du 10 Kronkorken.');
  end if;
  return new;
end $function$;
drop trigger if exists profile_referral on public.profiles;
