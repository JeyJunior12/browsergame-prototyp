-- Topf: 80 % der Einsätze der Woche + Jackpot aus Wochen ohne Gewinner + 20 € Grundstock
create or replace function public.kiez_lotto_pot(wk date) returns numeric language sql stable as $$
  select 20 + 0.8*2*(select count(*) from public.lotto_tickets where draw_week=wk)
       -- Jackpot: Topf der letzten Ziehung, falls niemand gewonnen hat (enthält bereits ältere Jackpots)
       + coalesce((select case when winners=0 then pot else 0 end from public.lotto_draws where draw_week<wk order by draw_week desc limit 1),0)
$$;

create or replace function public.resolve_lotto()
returns integer language plpgsql security definer set search_path to 'public' as $function$
declare wk date; num int; pot numeric; w int; prize numeric; t record; n int := 0;
begin
  for wk in select distinct draw_week from public.lotto_tickets where draw_week<public.kiez_week(current_date)
            and draw_week not in (select draw_week from public.lotto_draws) order by 1 loop
    num := 1+floor(random()*49)::int; pot := public.kiez_lotto_pot(wk);
    select count(*) into w from public.lotto_tickets where draw_week=wk and number=num;
    prize := case when w>0 then round(pot/w,2) else 0 end;
    insert into public.lotto_draws(draw_week,number,pot,winners,prize) values(wk,num,pot,w,prize);
    for t in select distinct user_id from public.lotto_tickets where draw_week=wk loop
      if exists(select 1 from public.lotto_tickets where draw_week=wk and user_id=t.user_id and number=num) then
        -- Lottogewinne werden voll ausgezahlt, auch über den Geldbehälter hinaus (Ausnahme von der Deckelung)
        update public.profiles set money=money+prize*(select count(*) from public.lotto_tickets where draw_week=wk and user_id=t.user_id and number=num) where id=t.user_id;
        perform public.kiez_notify(t.user_id,'lotto','🎰 LOTTO-GEWINN! Die Zahl war '||num||'. Du bekommst '||replace(to_char(prize,'FM999999990.00'),'.',',')||' € pro richtigem Los.');
      else
        perform public.kiez_notify(t.user_id,'lotto','Kiez-Lotto: Die Zahl war '||num||'. Leider kein Gewinn.');
      end if;
    end loop;
    n := n+1;
  end loop;
  return n;
end $function$;

create or replace function public.buy_lotto_ticket(chosen integer)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; wk date := public.kiez_week(current_date);
begin
  p := public.kiez_actor();
  perform public.resolve_lotto();
  if chosen is null or chosen not between 1 and 49 then raise exception 'Wähle eine Zahl von 1 bis 49'; end if;
  if (select count(*) from public.lotto_tickets where user_id=p.id and draw_week=wk)>=10 then raise exception 'Höchstens 10 Lose pro Woche'; end if;
  if p.money<2 then raise exception 'Ein Los kostet 2 €'; end if;
  update public.profiles set money=money-2 where id=p.id returning * into p;
  insert into public.lotto_tickets(user_id,draw_week,number) values(p.id,wk,chosen);
  return jsonb_build_object('number',chosen,'pot',public.kiez_lotto_pot(wk),'profile',to_jsonb(p));
end $function$;

create or replace function public.lotto_info()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare wk date := public.kiez_week(current_date);
begin
  perform public.resolve_lotto();
  return jsonb_build_object('pot',public.kiez_lotto_pot(wk),'draw_at',wk+7,
    'tickets',(select count(*) from public.lotto_tickets where draw_week=wk),
    'mine',(select coalesce(jsonb_agg(number order by id),'[]') from public.lotto_tickets where draw_week=wk and user_id=auth.uid()),
    'last',(select to_jsonb(d) from public.lotto_draws d order by draw_week desc limit 1));
end $function$;

-- ---------- Erfolgs-Fortschritt ohne Freischalten ----------
create or replace function public.kiez_stats(p public.profiles)
returns jsonb language sql stable security definer set search_path to 'public' as $$
  select jsonb_build_object(
    'bottles_total',(select coalesce(sum(progress),0) from public.daily_missions where user_id=p.id),
    'level',p.level,'wins',p.wins,'money',p.money,'bottle_money',p.bottles_lifetime_earned,
    'attack_skill',p.attack_skill,'defense_skill',p.defense_skill,'social_skill',p.social_skill,'music_level',p.music_level,
    'shelter_level',p.shelter_level,'area_level',p.area_level,'login_streak',p.login_streak,
    'pets',(select count(*) from public.user_pets where user_id=p.id),'pet_wins',p.pet_wins,
    'plunder_kinds',(select count(*) from public.user_plunder where user_id=p.id),
    'friends',(select count(*) from public.friendships where (user_id=p.id or friend_id=p.id) and status='accepted'),
    'in_gang',(select count(*) from public.gang_members where user_id=p.id),
    'donations',p.donations_received,
    'crimes',(select count(*) from public.side_action_log where user_id=p.id and action_type like 'crime:%' and success))
$$;
revoke execute on function public.kiez_stats(public.profiles) from public, anon, authenticated;

create or replace function public.check_achievements()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; st jsonb; unlocked jsonb := '[]'::jsonb; a record; paid numeric;
begin
  p := public.kiez_actor();
  st := public.kiez_stats(p);
  for a in select d.* from public.achievement_defs d
           where d.stat is not null and coalesce((st->>d.stat)::numeric,0) >= d.threshold
             and not exists(select 1 from public.user_achievements u where u.user_id=p.id and u.achievement_id=d.id)
           order by d.sort_order loop
    insert into public.user_achievements(user_id,achievement_id) values(p.id,a.id);
    select least(a.reward, greatest(0,cash_capacity-money)) into paid from public.profiles where id=p.id;
    update public.profiles set money=money+paid, bottlecaps=bottlecaps+a.reward_caps where id=p.id;
    perform public.kiez_notify(p.id,'erfolg','🎖 Erfolg „'||a.name||'“ freigeschaltet!');
    unlocked := unlocked || jsonb_build_array(jsonb_build_object('name',a.name,'reward',paid,'caps',a.reward_caps));
  end loop;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('unlocked',unlocked,'stats',st,'profile',to_jsonb(p));
end $function$;

create or replace function public.achievement_progress()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles;
begin
  select * into p from public.profiles where id=auth.uid();
  if p.id is null then raise exception 'Spielerprofil fehlt'; end if;
  return public.kiez_stats(p);
