create trigger profile_referral after update on public.profiles for each row when (new.level>=5 and old.level<5) execute function public.kiez_referral_reward();

-- ---------- Namensänderung (30 Kronkorken, höchstens alle 30 Tage) ----------
create or replace function public.change_username(new_name text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; clean text := trim(coalesce(new_name,''));
begin
  p := public.kiez_actor();
  if not public.valid_game_name(clean,3,20) then raise exception 'Name: 3 bis 20 Zeichen, nur Buchstaben, Zahlen, Leerzeichen, _ . -'; end if;
  if exists(select 1 from public.profiles where lower(username)=lower(clean) and id<>p.id) then raise exception 'Diesen Namen gibt es schon'; end if;
  if p.username_changed_at is not null and p.username_changed_at>now()-interval '30 days' then raise exception 'Den Namen kannst du nur alle 30 Tage ändern'; end if;
  if p.bottlecaps<30 then raise exception 'Eine Namensänderung kostet 30 Kronkorken'; end if;
  update public.profiles set username=clean, username_changed_at=now(), bottlecaps=bottlecaps-30 where id=p.id returning * into p;
  return to_jsonb(p);
end $function$;

-- ---------- Gegenstände verkaufen (50 % des Kaufpreises) ----------
create or replace function public.sell_item(wanted_item text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; inv public.inventory; it public.shop_items; price numeric(12,2); paid numeric(12,2);
begin
  p := public.kiez_actor();
  select * into inv from public.inventory where user_id=p.id and item_id=wanted_item for update;
  if inv.item_id is null or inv.quantity<1 then raise exception 'Das hast du nicht'; end if;
  if inv.equipped and inv.quantity<=1 then raise exception 'Leg den Gegenstand erst ab'; end if;
  select * into it from public.shop_items where id=wanted_item;
  price := round(coalesce(it.price,0)*0.5,2);
  paid := least(price, greatest(0,p.cash_capacity-p.money));
  if inv.quantity<=1 then delete from public.inventory where user_id=p.id and item_id=wanted_item;
  else update public.inventory set quantity=quantity-1 where user_id=p.id and item_id=wanted_item; end if;
  update public.profiles set money=money+paid where id=p.id returning * into p;
  return jsonb_build_object('item',it.name,'paid',paid,'lost',price-paid,'profile',to_jsonb(p));
end $function$;

