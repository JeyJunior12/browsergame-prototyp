-- ---------- Systemnachrichten ----------
create table if not exists public.notifications(
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null,
  body text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz);
create index if not exists notifications_user_idx on public.notifications(user_id, created_at desc);
alter table public.notifications enable row level security;
drop policy if exists "own notifications" on public.notifications;
create policy "own notifications" on public.notifications for select using (user_id = auth.uid());
grant select on public.notifications to authenticated;
revoke insert, update, delete, truncate on public.notifications from anon, authenticated;

create or replace function public.kiez_notify(uid uuid, k text, txt text)
returns void language sql security definer set search_path to 'public' as $$
  insert into public.notifications(user_id,kind,body) select uid,k,txt where uid is not null
$$;
revoke execute on function public.kiez_notify(uuid,text,text) from public, anon, authenticated;

create or replace function public.kiez_name(uid uuid) returns text language sql stable security definer set search_path to 'public' as
$$ select coalesce((select username from public.profiles where id=uid),'Jemand') $$;

