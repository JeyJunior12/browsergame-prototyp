create table if not exists public.races(
  id bigint generated by default as identity primary key,
  challenger_id uuid not null references public.profiles(id) on delete cascade, challenger_vehicle text not null,
  opponent_id uuid references public.profiles(id) on delete cascade, opponent_vehicle text,
  stake numeric(12,2) not null, created_at timestamptz not null default now(),
  starts_at timestamptz, resolved boolean not null default false, winner_id uuid, cp integer, op integer);
alter table public.races enable row level security;
drop policy if exists races_read on public.races;
create policy races_read on public.races for select using (true);
grant select on public.races to authenticated;
alter table public.bets drop constraint if exists bets_kind_check;
alter table public.bets add constraint bets_kind_check check (kind in ('war','pet','race'));

create or replace function public.kiez_race_power(uid uuid, vid text)
returns integer language sql stable security definer set search_path to 'public' as $$
  select coalesce((select v.speed*2 + v.bonus + case when (uv.tuning->>'motor')::boolean then 15 else 0 end + case when (uv.tuning->>'reifen')::boolean then 10 else 0 end + uv.condition/5
    from public.vehicles v join public.user_vehicles uv on uv.vehicle_id=v.id and uv.user_id=uid where v.id=vid),0)
$$;
create or replace function public.settle_races()
returns integer language plpgsql security definer set search_path to 'public' as $function$
declare r public.races; a int; b int; w uuid; n int := 0; pool numeric; winpool numeric; bt record; ws text;
begin
  for r in select * from public.races where not resolved and starts_at is not null and starts_at<=now() for update skip locked loop
    a := public.kiez_race_power(r.challenger_id,r.challenger_vehicle) + floor(random()*30)::int;
    b := public.kiez_race_power(r.opponent_id,r.opponent_vehicle) + floor(random()*30)::int;
    w := case when a>=b then r.challenger_id else r.opponent_id end; ws := case when a>=b then 'a' else 'b' end;
    update public.races set resolved=true, winner_id=w, cp=a, op=b where id=r.id;
    perform public.kiez_pay(w, round(r.stake*1.9,2));
    perform public.kiez_notify(r.challenger_id,'rennen',case when w=r.challenger_id then 'Rennen gewonnen! ' else 'Rennen verloren. ' end||a||' zu '||b||'.');
    perform public.kiez_notify(r.opponent_id,'rennen',case when w=r.opponent_id then 'Rennen gewonnen! ' else 'Rennen verloren. ' end||b||' zu '||a||'.');
    select sum(amount), sum(amount) filter (where side=ws) into pool, winpool from public.bets where kind='race' and ref=r.id::text and not settled;
    for bt in select * from public.bets where kind='race' and ref=r.id::text and not settled for update loop
      if coalesce(winpool,0)=0 then update public.bets set settled=true, payout=bt.amount where id=bt.id; perform public.kiez_pay(bt.user_id,bt.amount);
      elsif bt.side=ws then update public.bets set settled=true, payout=round(pool*0.95*bt.amount/winpool,2) where id=bt.id; perform public.kiez_pay(bt.user_id,round(pool*0.95*bt.amount/winpool,2));
      else update public.bets set settled=true, payout=0 where id=bt.id; end if;
    end loop;
    n := n+1;
  end loop;
  -- Offene Herausforderungen nach 24 Std. zurückgeben
  for r in select * from public.races where opponent_id is null and not resolved and created_at<now()-interval '24 hours' for update skip locked loop
    update public.races set resolved=true where id=r.id; perform public.kiez_pay(r.challenger_id, r.stake);
  end loop;
  return n;
end $function$;
revoke execute on function public.settle_races() from public, anon, authenticated;

create or replace function public.race_challenge(stake numeric)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; st numeric(12,2) := round(coalesce(stake,0),2); rid bigint;
begin
  p := public.kiez_actor();
  if coalesce((select sort_order from public.vehicles where id=p.vehicle),0) < 4 then raise exception 'Rennen nur mit Motorfahrzeug'; end if;
  if st < 5 or st > 500 then raise exception 'Einsatz 5 bis 500 €'; end if;
  if p.money < st then raise exception 'Dafür reicht deine Kohle nicht'; end if;
  if exists(select 1 from public.races where challenger_id=p.id and not resolved) then raise exception 'Du hast schon ein Rennen offen'; end if;
  update public.profiles set money=money-st where id=p.id;
  insert into public.races(challenger_id,challenger_vehicle,stake) values(p.id,p.vehicle,st) returning id into rid;
  return jsonb_build_object('id',rid);
end $function$;
create or replace function public.race_accept(race bigint)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; r public.races;
begin
  p := public.kiez_actor();
  select * into r from public.races where id=race and opponent_id is null and not resolved for update;
  if r.id is null then raise exception 'Das Rennen ist schon vergeben'; end if;
  if r.challenger_id=p.id then raise exception 'Nicht gegen dich selbst'; end if;
  if coalesce((select sort_order from public.vehicles where id=p.vehicle),0) < 4 then raise exception 'Rennen nur mit Motorfahrzeug'; end if;
  if p.money < r.stake then raise exception 'Dafür reicht deine Kohle nicht'; end if;
  update public.profiles set money=money-r.stake where id=p.id;
  update public.races set opponent_id=p.id, opponent_vehicle=p.vehicle, starts_at=now()+interval '10 minutes' where id=r.id;
  perform public.kiez_notify(r.challenger_id,'rennen',p.username||' nimmt dein Rennen an – Start in 10 Minuten, Zuschauer können wetten.');
  return jsonb_build_object('starts_at',now()+interval '10 minutes');
end $function$;
create or replace function public.race_bet(race bigint, bet_side text, amount numeric)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; r public.races; amt numeric(12,2) := round(coalesce(amount,0),2);
begin
  p := public.kiez_actor();
  select * into r from public.races where id=race and not resolved and starts_at>now();
  if r.id is null then raise exception 'Auf dieses Rennen kann man nicht (mehr) wetten'; end if;
  if p.id in (r.challenger_id,r.opponent_id) then raise exception 'Fahrer wetten nicht'; end if;
  if bet_side not in ('a','b') then raise exception 'Ungültige Seite'; end if;
  if amt < 0.5 or amt > 50 then raise exception 'Einsatz 0,50 € bis 50 €'; end if;
  if p.money < amt then raise exception 'Dafür reicht deine Kohle nicht'; end if;
  if exists(select 1 from public.bets where user_id=p.id and kind='race' and ref=race::text) then raise exception 'Du hast schon gewettet'; end if;
  update public.profiles set money=money-amt where id=p.id;
  insert into public.bets(user_id,kind,ref,side,amount) values(p.id,'race',race::text,bet_side,amt);
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('amount',amt,'profile',to_jsonb(p));
end $function$;
