create or replace function public.side_quests_status()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare me uuid := auth.uid();
begin
  if me is null then raise exception 'Nicht angemeldet'; end if;
  insert into public.side_quests(user_id,quest) select me, q from (values ('oma'),('kemal'),('ratte')) v(q) on conflict do nothing;
  return (select jsonb_agg(jsonb_build_object('quest',s.quest,'figure',d.figure,'step',s.step,'steps',(select max(step) from public.side_quest_defs x where x.quest=s.quest),
      'done',s.done,'title',d.title,'body',d.body,'kind',d.kind,'target',d.target,
      'progress',least(d.target,(select coalesce(sum(a.amount),0) from public.kiez_actions a where a.user_id=me and a.kind=d.kind and a.created_at>=s.started_at)),
      'reward_money',d.reward_money,'reward_caps',d.reward_caps,'reward_xp',d.reward_xp) order by s.quest)
    from public.side_quests s left join public.side_quest_defs d on d.quest=s.quest and d.step=s.step where s.user_id=me);
end $function$;

create or replace function public.claim_side_quest(q text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; s public.side_quests; d public.side_quest_defs; prog int; last_ int;
begin
  p := public.kiez_actor();
  select * into s from public.side_quests where user_id=p.id and quest=q for update;
  if s.user_id is null or s.done then raise exception 'Nichts abzuholen'; end if;
  select * into d from public.side_quest_defs where quest=q and step=s.step;
  select coalesce(sum(amount),0) into prog from public.kiez_actions where user_id=p.id and kind=d.kind and created_at>=s.started_at;
  if prog < d.target then raise exception 'Noch nicht geschafft (% von %)', prog, d.target; end if;
  select max(step) into last_ from public.side_quest_defs where quest=q;
  update public.side_quests set step=least(step+1,last_), started_at=now(), done=(step>=last_) where user_id=p.id and quest=q;
  update public.profiles set bottlecaps=bottlecaps+d.reward_caps, xp=xp+d.reward_xp where id=p.id;
  perform public.kiez_pay(p.id, d.reward_money);
  if q='ratte' then perform public.kiez_rep(p.id,-3,5,0); elsif q='oma' then perform public.kiez_rep(p.id,2,0,5); else perform public.kiez_rep(p.id,2,1,2); end if;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('figure',d.figure,'money',d.reward_money,'caps',d.reward_caps,'xp',d.reward_xp,'finished',s.step>=last_,'profile',to_jsonb(p));
end $function$;
create or replace function public.commit_crime(crime_id integer)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare
  p public.profiles;
  names text[]:=array['Handtaschenraub','Ladendiebstahl','Auto aufbrechen','Einbruch','Tankstellenüberfall','Bankraub','Kaugummiautomat aufbrechen'];
  risks int[]:=array[15,22,30,42,55,70,18];
  rewardmin numeric[]:=array[8,18,45,90,180,450,10];
  rewardmax numeric[]:=array[18,35,80,160,320,900,20];
  bails numeric[]:=array[8,18,35,70,150,400,10];
  jailmins int[]:=array[8,12,20,35,60,120,9];
  cost int[]:=array[6,8,10,14,18,22,7];
  idx int; caught boolean; reward numeric;
begin
  p := public.kiez_actor();
  perform public.kiez_assert_free(p);
  idx:=crime_id;
  if idx is null or idx<1 or idx>array_length(names,1) then raise exception 'Unbekanntes Verbrechen'; end if;
  if p.energy<cost[idx] then raise exception 'Dafür reicht deine Energie nicht'; end if;
  -- Razzia (22:00–22:30 Uhr): Polizei überall, Risiko +20 Punkte
  -- Razzia (22:00–22:30) +20, Razzia im eigenen Viertel +15, nachts +5; guter Ruf bei der Polizei schützt vor Razzien
  caught:=random()*100<risks[idx]
    + case when public.kiez_time()='razzia' and p.rep_police<30 then 20 else 0 end
    + case when public.kiez_district_event(p,'razzia') and p.rep_police<30 then 15 else 0 end
    + case when public.kiez_daytime()='nacht' then 5 else 0 end;
  if caught then
    update public.profiles set energy=energy-cost[idx],jail_until=now()+make_interval(mins=>jailmins[idx]),jail_bail=bails[idx] where id=p.id returning * into p;
    insert into public.side_action_log(user_id,action_type,success,money_change,xp_change) values(p.id,'crime:'||names[idx],false,0,0);
    return jsonb_build_object('caught',true,'name',names[idx],'bail',bails[idx],'jail_minutes',jailmins[idx],'profile',to_jsonb(p));
  end if;
  reward:=round((rewardmin[idx]+random()::numeric*(rewardmax[idx]-rewardmin[idx])),2);
  -- Nachts +20 %, Unterwelt-Ruf ab 50: +10 %
  reward:=round(reward*(1+case when public.kiez_daytime()='nacht' then 0.2 else 0 end+case when p.rep_underworld>=50 then 0.1 else 0 end),2);
  reward:=least(reward,greatest(0,p.cash_capacity-p.money));
  update public.profiles set energy=energy-cost[idx],money=money+reward,xp=xp+greatest(3,cost[idx]) where id=p.id returning * into p;
  insert into public.side_action_log(user_id,action_type,success,money_change,xp_change) values(p.id,'crime:'||names[idx],true,reward,greatest(3,cost[idx]));
  return jsonb_build_object('caught',false,'name',names[idx],'reward',reward,'profile',to_jsonb(p));
end $function$;

create or replace function public.kiez_beg_factors(p public.profiles)
returns jsonb language plpgsql stable security definer set search_path to 'public' as $function$
declare sym int; f_pet numeric; f_clean numeric; f_speech numeric;
begin
  select coalesce(max(pc.health*up.level),0) into sym from public.user_pets up join public.pet_catalog pc on pc.id=up.pet_id
  where up.user_id=p.id and up.active;
  f_pet := least(3.0, 1 + coalesce(sym,0)/200.0);
  f_clean := case public.kiez_clean_tier(p.cleanliness) when 'gepflegt' then 1.2 when 'normal' then 1.0 when 'schmuddelig' then 0.6 else 0.2 end;
  f_speech := 1 + least(p.speech_skill,150)*0.01;
  if public.kiez_time()='mittag' then f_clean := f_clean*1.2; end if;  -- Mittagspause 12–13 Uhr: +20 %
  if public.kiez_daytime()='nacht' then f_clean := f_clean*0.7; end if;            -- nachts gibt kaum einer was
  if p.rep_neighbors>=30 then f_clean := f_clean*1.1; end if;                        -- Nachbarn mögen dich
  f_clean := f_clean*(1+public.kiez_city_bonus('beg')/100.0);
  return jsonb_build_object('sympathy',sym,'pet',round(f_pet,3),'clean',round(f_clean,3),'speech',round(f_speech,3),
    'total',round(f_pet*f_clean*f_speech,3),'tier',public.kiez_clean_tier(p.cleanliness));
end $function$;
revoke execute on function public.kiez_beg_factors(public.profiles) from public, anon, authenticated;
