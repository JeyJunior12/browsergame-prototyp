create or replace function public.kiez_city_event_ensure()
returns void language plpgsql security definer set search_path to 'public' as $function$
declare k int; d text;
begin
  if exists(select 1 from public.city_events where starts_at > now()-interval '3 hours') then return; end if;
  k := floor(random()*5)::int;
  select id into d from public.districts order by random() limit 1;
  insert into public.city_events(kind,bonus,district,title,body,ends_at) values
   (case k when 0 then 'bottles' when 1 then 'beg' when 2 then 'xp' when 3 then 'bottles' else 'razzia' end,
    case k when 0 then 100 when 1 then 30 when 2 then 25 when 3 then 30 else 0 end,
    case when k=4 then d end,
    case k when 0 then 'Konzert im Stadtpark' when 1 then 'Weihnachtsmarkt-Stimmung' when 2 then 'Kiez-Fest' when 3 then 'Flohmarkt am Hafen' else 'Razzia im Viertel' end,
    case k when 0 then 'Eine Stunde lang: doppelt so viel Pfand auf allen Touren.' when 1 then 'Die Leute sind großzügig: Schnorren +30 %.'
           when 2 then 'Alle feiern: +25 % Punkte auf Pfandtouren.' when 3 then 'Überall leere Flaschen: Pfand +30 %.'
           else 'Die Polizei durchkämmt '||coalesce((select name from public.districts where id=d),'ein Viertel')||': Verbrechen dort deutlich riskanter.' end,
    now()+interval '1 hour');
end $function$;
