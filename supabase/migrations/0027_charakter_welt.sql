create or replace function public.buy_cosmetic(wanted text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; c public.cosmetics;
begin
  p := public.kiez_actor();
  select * into c from public.cosmetics where id=wanted; if c.id is null then raise exception 'Gibt es nicht'; end if;
  if exists(select 1 from public.user_cosmetics where user_id=p.id and cosmetic_id=wanted) then raise exception 'Hast du schon'; end if;
  if p.bottlecaps < c.price_caps then raise exception 'Dafür brauchst du % Kronkorken', c.price_caps; end if;
  update public.profiles set bottlecaps=bottlecaps-c.price_caps where id=p.id;
  insert into public.user_cosmetics(user_id,cosmetic_id) values(p.id,wanted);
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('bought',c.name,'profile',to_jsonb(p));
end $function$;
create or replace function public.use_cosmetic(k text, wanted text)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles;
begin
  p := public.kiez_actor();
  if wanted is not null and not exists(select 1 from public.user_cosmetics u join public.cosmetics c on c.id=u.cosmetic_id where u.user_id=p.id and u.cosmetic_id=wanted and c.kind=k) then raise exception 'Das hast du nicht'; end if;
  if k='frame' then update public.profiles set avatar_frame=wanted where id=p.id returning * into p;
  elsif k='titlecolor' then update public.profiles set title_color=wanted where id=p.id returning * into p;
  else raise exception 'Unbekannt'; end if;
  return jsonb_build_object('profile',to_jsonb(p));
end $function$;

