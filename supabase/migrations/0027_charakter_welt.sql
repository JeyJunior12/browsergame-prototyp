create or replace function public.send_gift(friend uuid, gift_kind text, ref text, qty integer)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; fname text; have int; what text;
begin
  p := public.kiez_actor();
  if not public.kiez_friends(p.id, friend) then raise exception 'Geschenke nur an Freunde'; end if;
  select username into fname from public.profiles where id=friend;
  if gift_kind='caps' then
    if qty < 1 or qty > 20 then raise exception '1 bis 20 Kronkorken'; end if;
    if (case when p.gifts_day=current_date then p.gifts_caps else 0 end) + qty > 20 then raise exception 'Höchstens 20 Kronkorken pro Tag verschenken'; end if;
    if p.bottlecaps < qty then raise exception 'So viele Kronkorken hast du nicht'; end if;
    update public.profiles set bottlecaps=bottlecaps-qty, gifts_caps=case when gifts_day=current_date then gifts_caps+qty else qty end, gifts_day=current_date where id=p.id;
    update public.profiles set bottlecaps=bottlecaps+qty where id=friend; what := qty||' Kronkorken';
  elsif gift_kind='plunder' then
    select quantity into have from public.user_plunder where user_id=p.id and plunder_id=ref for update;
    if coalesce(have,0) < 1 then raise exception 'Das hast du nicht'; end if;
    if p.equipped_plunder=ref and have<2 then raise exception 'Leg es erst ab'; end if;
    update public.user_plunder set quantity=quantity-1 where user_id=p.id and plunder_id=ref;
    delete from public.user_plunder where user_id=p.id and plunder_id=ref and quantity=0;
    perform public.kiez_give_plunder(friend, ref); what := (select name from public.plunder_catalog where id=ref);
  elsif gift_kind='bier' then
    if p.money < 1 then raise exception 'Ein Bier kostet 1 €'; end if;
    update public.profiles set money=money-1 where id=p.id;
    update public.profiles set energy=least(100,energy+10) where id=friend; what := 'ein Bier (+10 Energie)';
  else raise exception 'Unbekanntes Geschenk'; end if;
  perform public.kiez_notify(friend,'geschenk',p.username||' hat dir etwas geschenkt: '||what||'.');
  perform public.kiez_rep(p.id,0,0,1);
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('gift',what,'to',fname,'profile',to_jsonb(p));
end $function$;

