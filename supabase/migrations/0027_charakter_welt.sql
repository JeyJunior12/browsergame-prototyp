create or replace function public.spin_wheel()
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; r numeric := random()*100; slot int; label text; pl text;
begin
  p := public.kiez_actor();
  if p.wheel_day = current_date then raise exception 'Heute schon gedreht – morgen wieder'; end if;
  update public.profiles set wheel_day=current_date where id=p.id;
  if r < 20 then slot := 0; label := 'Niete – nur ein leerer Joghurtbecher.';
  elsif r < 40 then slot := 1; perform public.kiez_pay(p.id,0.50); label := '0,50 €';
  elsif r < 55 then slot := 2; perform public.kiez_pay(p.id,1.00); label := '1,00 €';
  elsif r < 70 then slot := 3; update public.profiles set bottlecaps=bottlecaps+2 where id=p.id; label := '2 Kronkorken';
  elsif r < 82 then slot := 4; update public.profiles set energy=least(100,energy+20) where id=p.id; label := '+20 Energie';
  elsif r < 92 then slot := 5; update public.profiles set bottlecaps=bottlecaps+5 where id=p.id; label := '5 Kronkorken';
  elsif r < 98 then slot := 6; pl := public.kiez_random_plunder(); perform public.kiez_give_plunder(p.id,pl); label := 'Plunder: '||(select name from public.plunder_catalog where id=pl);
  else slot := 7; perform public.kiez_pay(p.id,5.00); label := 'Hauptgewinn: 5,00 €!'; end if;
  select * into p from public.profiles where id=p.id;
  return jsonb_build_object('slot',slot,'label',label,'profile',to_jsonb(p));
end $function$;

