create or replace function public.duo_invite(friend uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles;
begin
  p := public.kiez_actor();
  if not public.kiez_friends(p.id, friend) then raise exception 'Nur mit Freunden'; end if;
  -- Liegt schon eine Einladung vom Freund vor → Duo startet (3 Stunden)
  if exists(select 1 from public.duo_invites where from_id=friend and to_id=p.id and created_at>now()-interval '1 hour') then
    delete from public.duo_invites where (from_id=friend and to_id=p.id) or (from_id=p.id and to_id=friend);
    update public.profiles set duo_with=case when id=p.id then friend else p.id end, duo_until=now()+interval '3 hours' where id in (p.id, friend);
    perform public.kiez_notify(friend,'duo',p.username||' ist dabei: 3 Stunden zu zweit auf Pfandtour – beide +15 % Flaschen, solange ihr gleichzeitig unterwegs seid.');
    return jsonb_build_object('status','active','until',now()+interval '3 hours');
  end if;
  insert into public.duo_invites(from_id,to_id) values(p.id,friend) on conflict (from_id,to_id) do update set created_at=now();
  perform public.kiez_notify(friend,'duo',p.username||' will mit dir zu zweit auf Pfandtour – unter Freunde einladen, um anzunehmen.');
  return jsonb_build_object('status','invited');
end $function$;

