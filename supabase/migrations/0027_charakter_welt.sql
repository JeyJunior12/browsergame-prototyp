create or replace function public.set_mentor(mentor uuid)
returns jsonb language plpgsql security definer set search_path to 'public' as $function$
declare p public.profiles; m public.profiles;
begin
  p := public.kiez_actor();
  if p.mentor_id is not null then raise exception 'Du hast schon einen Mentor'; end if;
  if p.level >= 20 then raise exception 'Mentoren gibt es nur bis Level 20'; end if;
  select * into m from public.profiles where id=mentor and not is_banned;
  if m.id is null or m.id=p.id then raise exception 'Spieler unbekannt'; end if;
  if m.level < 30 then raise exception 'Mentor muss mindestens Level 30 sein'; end if;
  if (select count(*) from public.profiles where mentor_id=m.id and level<20) >= 5 then raise exception 'Dieser Mentor hat schon 5 Schützlinge'; end if;
  update public.profiles set mentor_id=m.id where id=p.id returning * into p;
  perform public.kiez_notify(m.id,'mentor',p.username||' hat dich als Mentor gewählt. Für jeden 5. Level eures Schützlings gibt es für euch beide Belohnungen.');
  return jsonb_build_object('mentor',m.username);
end $function$;
-- Level 5/10/15/20 des Schützlings: beide +5 Kronkorken, Mentor zusätzlich 1 € je Level
create or replace function public.kiez_mentor_trigger()
returns trigger language plpgsql security definer set search_path to 'public' as $function$
declare l int;
begin
  if new.mentor_id is null or new.level <= old.level then return new; end if;
  for l in select x from generate_series(old.level+1,new.level) x where x % 5 = 0 and x <= 20 loop
    update public.profiles set bottlecaps=bottlecaps+5 where id in (new.id,new.mentor_id);
    perform public.kiez_pay(new.mentor_id, l);
    perform public.kiez_notify(new.mentor_id,'mentor','Dein Schützling '||new.username||' ist Level '||l||': +5 Kronkorken und '||l||' € für dich.');
    perform public.kiez_notify(new.id,'mentor','Level '||l||' mit Mentor geschafft: +5 Kronkorken.');
  end loop;
  return new;
end $function$;
